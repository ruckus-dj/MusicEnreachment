export function publicationGroupLabel(
	locale: Locale,
	key: string,
	defaultLabel: string,
) {
	const messageKey = groupMessageKeys[key];
	return messageKey ? publicationMessage(locale, messageKey) : defaultLabel;
}

export function publicationFieldLabel(
	locale: Locale,
	key: string,
	defaultLabel: string,
) {
	const messageKey = fieldMessageKeys[key];
	if (messageKey) return publicationMessage(locale, messageKey);
	if (locale === "en") return englishFieldLabels[key] ?? defaultLabel;
	return defaultLabel;
}
