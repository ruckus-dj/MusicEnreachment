export type PublicationMessage = keyof typeof publicationMessages.en;

export function publicationMessage(locale: Locale, key: PublicationMessage) {
	return publicationMessages[locale][key];
}

export function formatPublicationMessage(
	locale: Locale,
	key: PublicationMessage,
	values: Record<string, string | number>,
) {
	return publicationMessage(locale, key).replace(
		/\{([^}]+)\}/g,
		(_, name: string) => String(values[name] ?? `{${name}}`),
	);
}

