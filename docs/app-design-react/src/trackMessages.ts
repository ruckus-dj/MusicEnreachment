export type TrackMessage = keyof typeof trackMessages.en;

export function trackMessage(locale: Locale, key: TrackMessage) {
	return trackMessages[locale][key];
}

export function formatTrackMessage(
	locale: Locale,
	key: TrackMessage,
	values: Record<string, string | number>,
) {
	return trackMessage(locale, key).replace(/\{([^}]+)\}/g, (_, name: string) =>
		String(values[name] ?? `{${name}}`),
	);
}
