export type CatalogueMessage = keyof typeof catalogueMessages.en;

export function catalogueMessage(
	locale: Locale,
	key: CatalogueMessage,
	values: Record<string, string | number> = {},
): string {
	return catalogueMessages[locale][key].replace(
		/\{([^}]+)\}/g,
		(_, name: string) => String(values[name] ?? `{${name}}`),
	);
}
