export type SourceInspectorMessageKey = keyof typeof messages.en;

export function sourceInspectorMessage(
  locale: "en" | "ru",
  key: SourceInspectorMessageKey,
  values: Record<string, string | number> = {},
) {
  return messages[locale][key].replace(/\{([^}]+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

/** Safe localized notice for a missing file/source; carries no server detail. */
export function sourceInspectorNotFound(locale: "en" | "ru") {
  return sourceInspectorMessage(locale, "inspectorNotFound");
}
