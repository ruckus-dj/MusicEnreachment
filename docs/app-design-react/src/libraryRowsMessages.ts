export type LibraryRowsMessage = keyof typeof libraryRowsMessages.en;

export function libraryRowsMessage(
	locale: Locale,
	key: LibraryRowsMessage,
	values: Record<string, string | number> = {},
): string {
	return libraryRowsMessages[locale][key].replace(
		/\{([^}]+)\}/g,
		(_, name: string) => String(values[name] ?? `{${name}}`),
	);
}
