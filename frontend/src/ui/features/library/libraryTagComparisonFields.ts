/** Field labels are presentation only; stable keys and tags never vary by locale. */
export function libraryTagComparisonFieldLabel(
  key: string,
  locale: Locale,
): string {
  const labels: Record<string, string> = fieldLabels[locale];
  return labels[key] ?? key;
}

export interface LibraryTagComparisonField {
  key: string;
  label: string;
}

/**
 * Tag comparison fields for a locale: each stable writer tag plus its
 * localized label. A filter narrows the shared registry instead of
 * duplicating its key list.
 */
export function libraryTagComparisonFields(
  locale: Locale,
  filter?: (field: MetadataField) => boolean,
): LibraryTagComparisonField[] {
  return navidromeFields.filter(filter ?? (() => true)).map((field) => ({
    key: field.tag,
    label: libraryTagComparisonFieldLabel(field.key, locale),
  }));
}
