import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const { fallback, kinds } = JSON.parse(
  readFileSync(new URL("../frontend/src/ui/features/operations/operationKindLabels.json", import.meta.url)),
);
const output = new URL("../backend/internal/persistence/current_operations_kind_order_gen.go", import.meta.url);
const source = `// Code generated by tools/generate-operation-kind-order.mjs; DO NOT EDIT.
package persistence

var currentOperationKindOrder = map[string]operationKindOrder{
${["en", "ru"].map((locale) => {
  const collator = new Intl.Collator(locale, { sensitivity: "base", numeric: true });
  const captions = Object.entries(kinds).map(([kind, label]) => [kind, label[locale]]);
  captions.push(["", fallback[locale]]);
  captions.sort((a, b) => collator.compare(a[1], b[1]));
  const groups = [];
  let fallbackRank = -1;
  captions.forEach(([kind, caption], index) => {
    if (index === 0 || collator.compare(captions[index - 1][1], caption) !== 0) groups.push([]);
    if (kind) groups.at(-1).push(kind);
    else fallbackRank = groups.length - 1;
  });
  return `\t"${locale}": {fallback: ${fallbackRank}, groups: [][]string{\n${groups.map((group) => `\t\t{${group.map((kind) => JSON.stringify(kind)).join(", ")}},`).join("\n")}\n\t}},`;
}).join("\n")}
}
`;
writeFileSync(output, execFileSync("gofmt", { input: source }));
